#ifdef BUILD_SMS

#ifndef KEYMAP_H
#define KEYMAP_H

#include "joystick.h"

// Screen dimensions and layout for platform. Mode 4 shows exactly 32x24
// tiles (the original VDP has no 224-line mode), the Adam's grid, so the
// layout constants are the Adam's: the board ends on row 20 and the dice sit
// on rows 20-22 under the six player columns, covering the board's bottom
// rule only where they stand (src/sms/graphics.c puts it back). The art is
// the MS-DOS client's, on the MS-DOS board shifted eight cells left, as the
// NES port draws it.
#define WIDTH 32
#define HEIGHT 24

#define ROLL_SOUND_MOD 1 // How often to play roll sound
#define ROLL_FRAMES 11   // How many roll frames to play
#define BOTTOM_HEIGHT 3  // How high the bottom panel is
#define SCORES_X 2       // X start of scoreboard
#define GAMEOVER_PROMPT_Y HEIGHT-2
// The Adam's WIDTH-24: the roll button lands under the first player column,
// with the dice (WIDTH-20+4*i) under the other five.
#define ROLL_X WIDTH-24
#define TIMER_X 5
#define TIMER_NUM_OFFSET_X 2
#define TIMER_NUM_OFFSET_Y 1

#define QUERY_SUFFIX "" // Z80 is little endian - no &be=1 needed

// Icons - MS-DOS charset glyph numbers; graphics.c maps them through
// sheetTile[] (src/sms/tiles.h, generated by mktiles.py)
#define ICON_TEXT_CURSOR  0xD9
#define ICON_MARK         0x1D
#define ICON_MARK_ALT     0x1C
#define ICON_PLAYER       0x0A
#define ICON_SPEC         0xDC
#define ICON_CURSOR       0xBE
#define ICON_CURSOR_ALT   0xBF
#define ICON_CURSOR_BLIP  0x3E

/* readJoystick() (src/sms/input.c) returns the d-pad only, in joystick.h's
   bits. The buttons never appear in the joystick byte: input.c reports them as
   key codes behind kbhit()/cgetc(), with one edge detector, so a held button
   reports exactly once. Button 1 is KEY_RETURN, which readCommonInput() maps
   to the trigger and which also satisfies the screens that block on cgetc(). */
#undef JOY_BTN_1
#undef JOY_BTN_2
#define JOY_BTN_1(v) ((v) & 0)
#define JOY_BTN_2(v) ((v) & 0)

/**
 * Platform specific key map for common input
 */

// There is no keyboard: a d-pad, buttons 1 and 2, and Pause on the console.
// Direction comes from the d-pad, never from a key, so the arrow codes are
// deliberately unreachable placeholders -- they exist because
// readCommonInput() switches on all twelve.
#define KEY_LEFT_ARROW      0xF1
#define KEY_LEFT_ARROW_2    0xF2
#define KEY_LEFT_ARROW_3    0xF3

#define KEY_RIGHT_ARROW     0xF4
#define KEY_RIGHT_ARROW_2   0xF5
#define KEY_RIGHT_ARROW_3   0xF6

#define KEY_UP_ARROW        0xF7
#define KEY_UP_ARROW_2      0xF8
#define KEY_UP_ARROW_3      0xF9

#define KEY_DOWN_ARROW      0xFA
#define KEY_DOWN_ARROW_2    0xFB
#define KEY_DOWN_ARROW_3    0xFC

#define KEY_RETURN       0x0D
#define KEY_ESCAPE       0x1B
#define KEY_ESCAPE_ALT   0x03
#define KEY_SPACEBAR     0x20
#define KEY_BACKSPACE    0x08

// One pad, so one local player: the local player setup screen wants the keys
// 1-4 and A, which a pad cannot type.
#define SINGLE_LOCAL_PLAYER

// Name entry types from an on-screen letter grid (src/sms/osk.c). While it is
// open, kbhit()/cgetc() report what the grid types instead of the buttons.
#define ON_SCREEN_KEYBOARD
void oskOpen(void);
void oskClose(void);

// Button names for the shared screens' prompts. Button 2 is a shift, as on
// the other Master System clients; src/sms/input.c maps them, keep the two in
// step:
//   1        RETURN   trigger       Pause    ESCAPE   menu
//   2 alone  'r'      refresh       2+Up     'h'      how to play
//   2+Down   's'      sound         2+1      'q'      quit
#define ESCAPE "PAUSE"
#define ESC "PAUSE"
#define TRIGGER_TEXT "1"
#define LOBBY_STATUS_TEXT "2:refresh 2+UP:help 2+1:quit"
#define MENU_QUIT_TEXT "2+1:quit table"
#define MENU_HELP_TEXT "2+UP:how to play"
#define MENU_SOUND_ON_TEXT "2+DN:sound ON "
#define MENU_SOUND_OFF_TEXT "2+DN:sound OFF"
#define MENU_ESC_TEXT "PAUSE:keep playing"

#endif /* KEYMAP_H */

#endif /* BUILD_SMS */
