#ifdef BUILD_ATARI7800

#ifndef KEYMAP_H
#define KEYMAP_H

#include <joystick.h>

// Screen dimensions and layout for platform. The engine (maria.h) is the
// Adam's 32x24 grid, so the layout is the Adam's: the board's bottom rule
// (row 20) shares its row with the top of the dice, and the roll button sits
// one column right of the MS-DOS placement, so the dice cursor's left bar
// (graphics.c) clears the timer.
#define WIDTH 32
#define HEIGHT 24

#define ROLL_SOUND_MOD 1 // How often to play roll sound
#define ROLL_FRAMES 11   // How many roll frames to play
#define BOTTOM_HEIGHT 3  // How high the bottom panel is
#define SCORES_X 2       // X start of scoreboard
#define GAMEOVER_PROMPT_Y HEIGHT-2
#define ROLL_X WIDTH-24
#define TIMER_X 5
#define TIMER_NUM_OFFSET_X 2
#define TIMER_NUM_OFFSET_Y 1

#define QUERY_SUFFIX "" // 6502 is little endian - no &be=1 needed

// Icons - MS-DOS charset glyph numbers; graphics.c maps them through
// sheetTile[] (src/atari7800/tiles.h, generated by mkchr.py)
#define ICON_TEXT_CURSOR  0xD9
#define ICON_MARK         0x1D
#define ICON_MARK_ALT     0x1C
#define ICON_PLAYER       0x0A
#define ICON_SPEC         0xDC
#define ICON_CURSOR       0xBE
#define ICON_CURSOR_ALT   0xBF
#define ICON_CURSOR_BLIP  0x3E

/* readJoystick() (src/atari7800/input.c) returns the stick only, as cc65's
   joystick bits. The buttons and console switches never appear in the
   joystick byte: input.c reports them as key codes behind kbhit()/cgetc(),
   with one edge detector, so a held button reports exactly once. Button 1 is
   KEY_RETURN, which readCommonInput() maps to the trigger and which also
   satisfies the screens that block on cgetc() ("press any key"). */
#undef JOY_BTN_1
#undef JOY_BTN_2
#define JOY_BTN_1(v) ((v) & 0)
#define JOY_BTN_2(v) ((v) & 0)

/**
 * Platform specific key map for common input
 */

// There is no keyboard: a joystick and the console switches. Direction comes
// from the stick, never from a key, so the arrow codes are deliberately
// unreachable placeholders -- they exist because readCommonInput() switches
// on all twelve.
#define KEY_LEFT_ARROW      0xF1
#define KEY_LEFT_ARROW_2    0xF2
#define KEY_LEFT_ARROW_3    0xF3

#define KEY_RIGHT_ARROW     0xF4
#define KEY_RIGHT_ARROW_2   0xF5
#define KEY_RIGHT_ARROW_3   0xF6

#define KEY_UP_ARROW        0xF7
#define KEY_UP_ARROW_2      0xF8
#define KEY_UP_ARROW_3      0xF9

#define KEY_DOWN_ARROW      0xFA
#define KEY_DOWN_ARROW_2    0xFB
#define KEY_DOWN_ARROW_3    0xFC

#define KEY_RETURN       0x0D
#define KEY_ESCAPE       0x1B
#define KEY_ESCAPE_ALT   0x03
#define KEY_SPACEBAR     0x20
#define KEY_BACKSPACE    0x08

// The left joystick only, so one local player: the local player setup screen
// wants the keys 1-4 and A, which a joystick cannot type.
#define SINGLE_LOCAL_PLAYER

// Name entry types from an on-screen letter grid (src/atari7800/osk.c). While
// it is open, kbhit()/cgetc() report what the grid types instead of the
// buttons.
#define ON_SCREEN_KEYBOARD
void oskOpen(void);
void oskClose(void);

// The joystick's buttons and the console switches, as readButtons() reports
// them (src/atari7800/input.c).
#define BTN_FIRE   0x01
#define BTN_2      0x02
#define BTN_SELECT 0x04
#define BTN_PAUSE  0x08
#define BTN_RESET  0x10
void initJoystick(void);
unsigned char readStick(void);
unsigned char readButtons(void);

// Button and switch names for the shared screens' prompts (see input.c for
// the map). Button 1 is FIRE; button 2 is "2", as CONFIG names it.
#define ESCAPE "PAUSE"
#define ESC "PAUSE"
#define TRIGGER_TEXT "FIRE"
#define LOBBY_STATUS_TEXT "2:help SEL:refresh RESET:quit"
#define MENU_QUIT_TEXT "RESET:quit table"
#define MENU_HELP_TEXT "2:how to play"
#define MENU_SOUND_ON_TEXT "SEL+2:sound ON "
#define MENU_SOUND_OFF_TEXT "SEL+2:sound OFF"
#define MENU_ESC_TEXT "PAUSE:keep playing"

#endif /* KEYMAP_H */

#endif /* BUILD_ATARI7800 */
