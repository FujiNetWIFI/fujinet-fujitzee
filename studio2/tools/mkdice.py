#!/usr/bin/env python3
"""mkdice.py OUT.inc -- the six die faces as app glyphs.

A glyph is 4 pixels by 12 scanlines, so a die is two glyphs side by side: 8
pixels by 12 lines, boxed top and bottom as well as the sides. The line above
a die and the line below it are the box, so dice stacked in a column are
separated by a double rule. Pips are one pixel wide (the centre one two) and
two lines tall; the glyph row's bit 3 is its leftmost pixel.

The art is printed to stderr with -v so the faces can be eyeballed.
"""
import sys

W, H = 8, 12
PIPX = {'L': (2,), 'C': (3, 4), 'R': (5,)}
PIPY = {'T': (2, 3), 'M': (5, 6), 'B': (8, 9)}
FACES = {
    1: ['MC'],
    2: ['TL', 'BR'],
    3: ['TL', 'MC', 'BR'],
    4: ['TL', 'TR', 'BL', 'BR'],
    5: ['TL', 'TR', 'MC', 'BL', 'BR'],
    6: ['TL', 'TR', 'ML', 'MR', 'BL', 'BR'],
}


def face(n):
    g = [[0] * W for _ in range(H)]
    for x in range(W):
        g[0][x] = g[H - 1][x] = 1
    for y in range(H):
        g[y][0] = g[y][W - 1] = 1
    for pip in FACES[n]:
        for x in PIPX[pip[1]]:
            for y in PIPY[pip[0]]:
                g[y][x] = 1
    return g


def nib(row):
    return sum(bit << (3 - i) for i, bit in enumerate(row))


def main():
    out = sys.argv[1]
    lines = ['; GENERATED by tools/mkdice.py -- do not edit.',
             '; code, 12 scanline rows (bit 3 the leftmost pixel); 0 ends.',
             'gtab:']
    for n in range(1, 7):
        g = face(n)
        for half in (0, 1):
            code = 0x80 + 2 * (n - 1) + half
            rows = [nib(r[4 * half:4 * half + 4]) for r in g]
            lines.append('        DB      0%02XH, ' % code +
                         ', '.join('%02XH' % v if v > 9 else '%d' % v for v in rows))
        if '-v' in sys.argv:
            print('face', n, file=sys.stderr)
            for r in g:
                print(''.join('#' if v else '.' for v in r), file=sys.stderr)
    lines.append('        DB      0')
    open(out, 'w').write('\n'.join(lines) + '\n')


main()
